"""Builds the ISO/IEC 25010 evaluation instrument (consent, profile, questionnaire, CESU validation).

Usage: python build_evaluation_instrument.py <out.docx>
Reuses the TUP letterhead logos in docs/Final Defense Revision/letterhead/.
"""
