doc = Document()
sec = doc.sections[0]
sec.page_width, sec.page_height = Inches(8.27), Inches(11.69)
sec.top_margin, sec.bottom_margin = Inches(1.45), Inches(0.8)
sec.left_margin = sec.right_margin = Inches(1)
sec.header_distance = Inches(0.35)
normal = doc.styles["Normal"]
normal.font.name = "Times New Roman"
normal.font.size = Pt(11)
normal.paragraph_format.space_after = Pt(0)


def para(text="", bold=False, italic=False, align=None, after=4, size=None, before=0):
    p = doc.add_paragraph()
    if text:
        r = p.add_run(text)
        r.bold, r.italic = bold, italic
        if size:
            r.font.size = Pt(size)
    if align is not None:
        p.alignment = align
    p.paragraph_format.space_after = Pt(after)
    p.paragraph_format.space_before = Pt(before)
    return p


def fixed_table(rows, widths, borders=True):
    t = doc.add_table(rows=rows, cols=len(widths))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    layout = OxmlElement("w:tblLayout")
    layout.set(qn("w:type"), "fixed")
    t._tbl.tblPr.append(layout)
    if borders:
        t.style = "Table Grid"
    for col, w in zip(t.columns, widths):
        col.width = Inches(w)
    for row in t.rows:
        for cell, w in zip(row.cells, widths):
            cell.width = Inches(w)
    return t


def cell_text(cell, text, bold=False, align=None, size=None):
    p = cell.paragraphs[0]
    r = p.add_run(text)
    r.bold = bold
    if size:
        r.font.size = Pt(size)
    if align is not None:
        p.alignment = align


def shade(cell, hex_fill):
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_fill)
    tc_pr.append(shd)


def blank_line(label, width_in=6.27):
    p = para(f"{label} ", after=6)
    p.add_run("_" * int((width_in * 72 - len(label) * 6) / 6.2))


def page_break():
    doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)


